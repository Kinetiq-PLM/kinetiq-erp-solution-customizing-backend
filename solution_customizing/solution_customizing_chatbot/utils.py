# --- process_user_input  ---
def process_user_input(user_input, conversation_id, employee_id):
    if len(user_input) > MAX_INPUT_LENGTH:
        return {
            "intent": "error",
            "answer": f"Your input exceeds the maximum length of {MAX_INPUT_LENGTH} characters. Please shorten your message.",
            "sql_query": None
        }
    
    user = User.objects.get(employee_id=employee_id)
    role = RolePerm.objects.get(role_id=user.role_id)
    access_data = get_accessible_schema_and_reports(role.role_name)
    # print(f"User: {user.employee_id}, Role: {role.role_name}, Role Description: {role.description}, Access Data: {access_data}")
    if not access_data:
        return {
            "intent": "unrecognized",
            "answer": f"Sorry, I'm unable to determine access permissions for role: {role.role_name}",
            "sql_query": None
        }


    formatted_reports = "\n".join(f"- {report}" for report in access_data["reports"])
    print(f"Formatted reports: {formatted_reports}")



    input_dict = {
        "input": user_input,
        "conversation_id": conversation_id,
        "accessible_schema": access_data["schema"],
        "accessible_reports": formatted_reports,
    }

    try:
        if not AGENT_CHAIN:
            raise ValueError("LangChain agent chain is not initialized.")
        response = AGENT_CHAIN.invoke(input_dict)
        clean_text = (response.strip()
                .removeprefix("'''json")
                .removeprefix("```json")
                .removesuffix("'''")
                .removesuffix("```"))
        return json.loads(clean_text)
    except json.JSONDecodeError:
        print(f"JSONDecodeError processing LLM response: {response}")
        return {
            "intent": "error",
            "answer": "I'm having trouble generating a proper response format. Please try rephrasing.",
            "sql_query": None
        }
    except Exception as e:
        print(f"Error during chain invocation or processing: {e}")
        return {
            "intent": "error",
            "answer": f"An internal error occurred while processing your request: {str(e)}",
            "sql_query": None
        }


# --- analyze_sql_results ---
def analyze_sql_results(results, user_input, conversation_id):
    formatted_results = json.dumps(results, default=str)

    analysis_prompt_text = f"""You are an assistant tasked with summarizing database query results into a *single, concise natural language sentence*.
    The user originally asked: "{user_input}"
    The database query returned the following data (this data will be displayed to the user separately as a table):
    {formatted_results}

    Your task is to provide *only* a brief introductory sentence or summary based on the data provided, suitable for preceding the table display. Do *not* list the data items themselves in your response. Focus solely on a high-level interpretation (e.g., "Here is the list of assets you requested," or "The query returned 5 assets."). 
    If the results are a single value (like a count or sum), provide that value in the summary sentence (e.g., "The total number of assets is 10.").

    If the results are empty, state that clearly.

    Generate a JSON response with an "answer" field containing *only* this single summary sentence.
    Example JSON (Good): {{"answer": "The sum of all the total sales amount is 123.23."}}
    Example JSON (Good): {{"answer": "The query returned 10 assets matching your criteria."}}
    Example JSON (Bad): {{"answer": "Here is the list: * Asset A * Asset B"}}

    Analysis (generate only the summary sentence for the 'answer' field):
    """

    input_dict = {
        "input": analysis_prompt_text,
        "conversation_id": conversation_id
    }

    try:
        if not AGENT_CHAIN:
            raise ValueError("LangChain agent chain is not initialized.")
        response = AGENT_CHAIN.invoke(input_dict)
        clean_text = (response.strip()
                    .removeprefix("```json")
                    .removeprefix("'''json")
                    .removesuffix("```")
                    .removesuffix("'''"))
        json_response = json.loads(clean_text)
        return json_response.get("answer", "Analysis could not be generated.")
    except json.JSONDecodeError:
        print(f"JSONDecodeError processing analysis response: {response}")
        return (response.strip()
                .removeprefix("```")
                .removeprefix("'''")
                .removesuffix("```")
                .removesuffix("'''"))
    except Exception as e:
        print(f"Error during analysis chain invocation or processing: {e}")
        return f"Error analyzing results: {str(e)}"


