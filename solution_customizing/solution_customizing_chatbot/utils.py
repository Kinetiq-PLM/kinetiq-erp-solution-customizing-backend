# --- execute_query to use django.db.connection ---
def execute_query(query):
    """Execute SQL query using Django's connection and return results"""
    if not query:
        return {"headers": [], "rows": [], "error": "No SQL query provided"}

    try:
        with connection.cursor() as cursor:
            cursor.execute(query)

            if cursor.description:
                column_names = [col[0] for col in cursor.description]
                rows = cursor.fetchall()

                formatted_rows = []
                for row in rows:
                    formatted_row = []
                    for item in row:
                        if isinstance(item, (datetime, date)):
                            formatted_row.append(item.isoformat())
                        elif isinstance(item, Decimal):
                            formatted_row.append(float(item))
                        else:
                            formatted_row.append(item)
                    formatted_rows.append(formatted_row)

                return {
                    "headers": column_names,
                    "rows": formatted_rows
                }
            else:
                return {"headers": [], "rows": [], "message": "Query executed successfully, no data returned."}

    except Exception as e:
        print(f"Error executing query via Django connection: {e}")
        return {"headers": [], "rows": [], "error": str(e)}

def get_role_description(role_name):
    """
    Get role description using Django ORM
    """
    try:
        # Use the RolePerm model directly
        role = RolePerm.objects.get(role_name=role_name)
        return role.description
        
    except RolePerm.DoesNotExist:
        print(f"Role '{role_name}' not found")
        return None
    except Exception as e:
        print(f"Error fetching role description: {e}")
        return None

def get_accessible_schema_and_reports(role_name):
    """
    Get accessible schema and reports based on role, handling multi-department roles
    """
    # Find all departments where this role exists
    departments = []
    for dept, roles in DEPT_ROLE_MAP.items():
        # print(f"Checking department: {dept}, roles: {roles}")
        if role_name in roles:
            print(f"Role '{role_name}' found in department '{dept}'")
            departments.append(dept)
    
    if not departments:
        return None

    # Get role permissions
    role_data = get_role_description(role_name)
    if not role_data:
        return None
        
    # Initialize containers for multi-department access
    accessible_reports = []
    accessible_schema = {}

    # Gather reports and schema from all relevant departments
    for department in departments:
        # Add department's reports
        dept_reports = department_reports_map.get(department, [])
        accessible_reports.extend(dept_reports)
        
        # Add department's schema
        dept_schema = DB_SCHEMA.get(department, {})
        accessible_schema[department] = dept_schema

    return {
        "departments": departments,
        "description": role_data,
        "reports": accessible_reports,
        "schema": accessible_schema
    }

# --- Helper function to load history from DB ---
def _load_chat_history_from_db(conversation_id, limit=MAX_MEMORY_INTERACTIONS):
    if not conversation_id:
        return {"chat_history": []}

    try:
        messages = Message.objects.filter(conversation_id=conversation_id).order_by('-created_at')[:limit * 2]
        messages = reversed(messages)

        history_messages = []
        for msg in messages:
            if msg.sender == 'user':
                history_messages.append(HumanMessage(content=msg.message))
            elif msg.sender == 'bot':
                history_messages.append(AIMessage(content=msg.message))

        return {"chat_history": history_messages}
    except Exception as e:
        print(f"Error loading chat history for conversation {conversation_id}: {e}")
        return {"chat_history": []}


